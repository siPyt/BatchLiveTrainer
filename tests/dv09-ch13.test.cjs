test('User settings script: only uncommented lines count; exactly one INIT line; thresholds are read from the active Const lines', () => {
  const base = settings.USER_REF_SCRIPT
  let p = settings.parseUserSettings(base)
  assert.deepEqual([p.enabled, p.error, p.process, p.device], [false, null, null, null])
  const lines = base.split('\r\n')
  const edit = (re, fn) => lines.map(l => (re.test(l) ? fn(l) : l)).join('\r\n')
  const both = edit(/^'#Const INIT_ALARM_THRESHOLD = 1/, l => l.slice(1))
  assert.match(settings.parseUserSettings(both).error, /only ONE/)
  const none = edit(/^#Const INIT_ALARM_THRESHOLD = 0/, l => "'" + l)
  assert.match(settings.parseUserSettings(none).error, /No INIT_ALARM_THRESHOLD/)
  const enabled = both.split('\r\n').map(l => (/^#Const INIT_ALARM_THRESHOLD = 0/.test(l) ? "'" + l : l)).join('\r\n')
  p = settings.parseUserSettings(enabled)
  assert.deepEqual([p.enabled, p.error], [true, null])
  const device6 = enabled.replace("'Const DEVICE_THRESHOLD_DEFAULT = 7", 'Const DEVICE_THRESHOLD_DEFAULT = 6')
  assert.equal(settings.parseUserSettings(device6).device, 6)
  assert.equal(settings.parseUserSettings(enabled.replace("'Const DEVICE_THRESHOLD_DEFAULT = 7", "Const DEVICE_THRESHOLD_DEFAULT = 7")).device, 7)
})

test('Adding a Column to Alarm List: the steps verify in order from the Quick Edit session and the saved display', () => withDefaults(() => {
  assert.deepEqual(Object.values(verdicts()).slice(0, 8), Array(8).fill('pending').slice(0, 8).map((_, i) => verdicts()['dv09-13c-' + (i + 1)]))
  assert.equal(Object.entries(verdicts()).filter(([id, v]) => id.startsWith('dv09-13c') && v === 'verified').length, 0)
  log('alarmList', 'Alarm List opened (DeltaV Operate Run)')
  assert.equal(verdicts()['dv09-13c-1'], 'verified')
  assert.match(settings.saveAlarmList(), /Quick Edit first/)
  settings.startQuickEdit()
  assert.equal(verdicts()['dv09-13c-2'], 'verified')
  log('alarmList', 'Alarm Summary Configuration opened (DeltaV.DVAlarmSummary Object Properties)')
  log('alarmList', 'Alarm Summary Configuration: Columns tab')
  assert.deepEqual(['dv09-13c-3', 'dv09-13c-4'].map(id => verdicts()[id]), ['verified', 'verified'])
  assert.equal(verdicts()['dv09-13c-5'], 'pending')
  const columns = [...settings.effectiveAlarmColumns(settings.useDv09Ops.getState())]
  assert.deepEqual(columns, ['timeIn', 'module', 'description', 'alarm', 'value', 'priority'], 'the default Alarm List columns')
  log('alarmList', 'Alarm Summary Configuration: Category added to Displayed Columns')
  assert.equal(verdicts()['dv09-13c-5'], 'pending', 'the column is not in the displayed list yet')
  assert.match(settings.applyAlarmColumns([]), /at least one/)
  assert.match(settings.applyAlarmColumns(['timeIn', 'bogus']), /Unknown/)
  assert.equal(settings.applyAlarmColumns([...columns, 'category']), null)
  assert.equal(verdicts()['dv09-13c-5'], 'verified')
  assert.equal(verdicts()['dv09-13c-6'], 'pending', 'Category is last, not fourth')
  assert.equal(settings.applyAlarmColumns(['timeIn', 'module', 'category', 'description', 'alarm', 'value', 'priority']), null)
  assert.equal(verdicts()['dv09-13c-6'], 'verified')
  assert.equal(verdicts()['dv09-13c-7'], 'pending', 'applied is not saved')
  assert.deepEqual(settings.effectiveAlarmColumns(settings.useDv09Ops.getState()), columns, 'Run still shows the saved columns')
  assert.equal(settings.saveAlarmList(), null)
  assert.equal(verdicts()['dv09-13c-7'], 'pending', 'saved but not closed')
  settings.closeQuickEdit()
  assert.equal(verdicts()['dv09-13c-7'], 'verified')
  assert.equal(verdicts()['dv09-13c-8'], 'pending', 'the Alarm List must be opened again')
  log('alarmList', 'Alarm List opened (DeltaV Operate Run)')
  assert.equal(verdicts()['dv09-13c-8'], 'verified')
  assert.deepEqual(settings.effectiveAlarmColumns(settings.useDv09Ops.getState()).slice(0, 4), ['timeIn', 'module', 'category', 'description'])
}))

test('Alarm List columns: closing Quick Edit without saving discards the applied change', () => withDefaults(() => {
  settings.startQuickEdit()
  assert.equal(settings.applyAlarmColumns(['timeIn', 'module', 'category', 'alarm']), null)
  assert.equal(settings.alarmListDirty(settings.useDv09Ops.getState()), true)
  settings.closeQuickEdit()
  assert.equal(settings.alarmListDirty(settings.useDv09Ops.getState()), false)
  assert.equal(settings.useDv09Ops.getState().alarmListColumns, null)
  assert.equal(verdicts()['dv09-13c-7'], 'pending')
  settings.startQuickEdit(); settings.applyAlarmColumns(['timeIn', 'module', 'alarm', 'category'])
  settings.saveAlarmList(); settings.closeQuickEdit(); log('alarmList', 'Alarm List opened (DeltaV Operate Run)')
  assert.equal(verdicts()['dv09-13c-7'], 'pending', 'Category is last: not the fourth column')
  assert.equal(verdicts()['dv09-13c-8'], 'pending')
}))

test('Adding Device Alarms to Banner: User_Ref, Save As, script edits, save and run verify step by step; unsaved script and the shortcut panel do not count', () => withDefaults(() => {
  const v = () => Object.fromEntries(dv09ChapterFor('dv09-ch13-banner').check(ctxOf()).map(c => [c.id, c.verdict]))
  assert.equal(Object.values(v()).filter(x => x === 'verified').length, 0)
  log('DeltaV Operate', 'Operate switched to Configure')
  assert.equal(v()['dv09-13b-1'], 'verified')
  operate.ensureStandardPictures()
  assert.ok(usePictures.getState().pictures.USER_REF, 'User_Ref ships in the Standard folder')
  assert.match(settings.saveAsPicture('USER_REF', '1Bad'), /letters/)
  assert.equal(settings.saveAsPicture('USER_REF', 'UserSettings'), null)
  assert.match(settings.saveAsPicture('USER_REF', 'UserSettings'), /already exists/)
  assert.equal(v()['dv09-13b-2'], 'verified')
  assert.equal(v()['dv09-13b-3'], 'pending')
  log('USERSETTINGS', 'Script editor opened: UserSettings.grf (Edit Script)')
  assert.equal(v()['dv09-13b-3'], 'verified')
  log('USERSETTINGS', 'Script editor Find: alarms')
  assert.equal(v()['dv09-13b-4'], 'verified')
  assert.equal(v()['dv09-13b-5'], 'pending')
  const script = usePictures.getState().pictures.USERSETTINGS.script
  let edited = script.replace('#Const INIT_ALARM_THRESHOLD = 0', "'#Const INIT_ALARM_THRESHOLD = 0").replace("'#Const INIT_ALARM_THRESHOLD = 1", '#Const INIT_ALARM_THRESHOLD = 1')
  assert.equal(settings.setPictureScript('USERSETTINGS', edited), null)
  assert.equal(v()['dv09-13b-5'], 'verified')
  assert.equal(v()['dv09-13b-6'], 'pending')
  edited = edited.replace("'Const DEVICE_THRESHOLD_DEFAULT = 7", 'Const DEVICE_THRESHOLD_DEFAULT = 7')
  settings.setPictureScript('USERSETTINGS', edited)
  assert.equal(v()['dv09-13b-6'], 'pending', 'the value 7 is still the default')
  settings.setPictureScript('USERSETTINGS', edited.replace('Const DEVICE_THRESHOLD_DEFAULT = 7', 'Const DEVICE_THRESHOLD_DEFAULT = 6'))
  assert.equal(v()['dv09-13b-6'], 'verified')
  assert.equal(v()['dv09-13b-7'], 'pending', 'the picture is not saved')
  assert.equal(settings.runUserSettings().applied, false, 'an unsaved UserSettings does not run')
  assert.equal(useUi.getState().bannerThresholds.device, 7)
  assert.equal(useUi.getState().setBannerThresholds({ process: 3, device: 6 }), null, 'the Banner settings shortcut')
  assert.equal(v()['dv09-13b-7'], 'pending', 'the shortcut is not the workshop')
  useUi.setState({ bannerThresholds: { process: 3, device: 7 } })
  assert.equal(operate.savePicture('USERSETTINGS'), null)
  assert.equal(v()['dv09-13b-7'], 'pending', 'saved but DeltaV Operate has not initialized yet')
  const r = settings.runUserSettings()
  assert.deepEqual([r.applied, r.process, r.device], [true, 3, 6])
  assert.equal(useUi.getState().bannerThresholds.device, 6)
  assert.equal(v()['dv09-13b-7'], 'verified')
}))

test('UserSettings with initialization disabled or a script error leaves the banner at the defaults', () => withDefaults(() => {
  operate.ensureStandardPictures()
  settings.saveAsPicture('USER_REF', 'UserSettings')
  operate.savePicture('USERSETTINGS')
  assert.deepEqual(settings.runUserSettings().applied, true, 'INIT = 0: the defaults are applied')
  assert.deepEqual([useUi.getState().bannerThresholds.process, useUi.getState().bannerThresholds.device], [3, 7])
  settings.setPictureScript('USERSETTINGS', settings.USER_REF_SCRIPT.replace("'#Const INIT_ALARM_THRESHOLD = 1", '#Const INIT_ALARM_THRESHOLD = 1'))
  operate.savePicture('USERSETTINGS')
  const r = settings.runUserSettings()
  assert.equal(r.applied, false)
  assert.match(r.reason, /only ONE/)
}))

test('Chapter 13 setup performs both workshops: all checks verified and an advisory device alarm reaches the banner only after the threshold change', () => withDefaults(ctx => {
  const c = Object.assign(Object.create(null), { M, useStore, eng: engine, assert })
  setup12(c)
  // commission the 3144P as TT1 and raise its advisory condition
  const CARD = 'CTLR_PAINT/C05'
  const row = act.ffInventory(M().hardware.h1Cards[CARD], 'P01')[0]
  assert.equal(act.addFfDevice(CARD, 'P01', 'TT1', row.address, 'RM-3144P', row.revision, row.ddRevision), null)
  assert.equal(act.commissionFfDevice(CARD, 'TT1', row.deviceId, 'Commissioned from DeltaV Explorer'), null)
  useStore.setState({ running: true })
  assert.equal(act.setFieldDevice(CARD, row.deviceId, { faults: { advisory: true } }), null)
  for (let i = 0; i < 40; i++) M().tick(0.1)
  const advisory = M().alarms.find(a => a.id === 'DEVALM.TT1.ADVISORY')
  assert.ok(advisory, 'the device advisory alarm is active in the Alarm List')
  assert.equal(advisory.rank, 7)
  assert.equal(alarmsApi.bannerVisible(advisory, useUi.getState().bannerThresholds), false, 'priority 7 is not above the default device threshold 7')
  setup13(c)
  assert.equal(useUi.getState().bannerThresholds.device, 6)
  assert.equal(alarmsApi.bannerVisible(advisory, useUi.getState().bannerThresholds), true)
  assert.deepEqual(settings.effectiveAlarmColumns(settings.useDv09Ops.getState()).slice(0, 4), ['timeIn', 'module', 'category', 'description'])
  const results = dv09ChapterFor('dv09-ch13-banner').check(ctxOf())
  assert.equal(results.length, 15)
  for (const r of results) assert.equal(r.verdict, 'verified', r.id + ': ' + r.detail)
}))
