test('Chapter 13: recipe authorization needs every signer; a new signer un-authorizes; downloads are blocked until authorized', () => fixture(() => {
  enable()
  value(V().setAuthorization(true, [{ name: 'ENGINEER', lock: 'VC_SET_LABEL' }], false))
  assert.equal(V().setAuthorization(true, [{ name: 'A', lock: 'X' }, { name: 'B', lock: 'X' }], false).ok, false, 'a lock can be assigned once')
  assert.equal(V().setAuthorization(true, new Array(6).fill(0).map((_, i) => ({ name: `S${i}`, lock: `L${i}` })), false).ok, false, 'up to five signers')
  assert.equal(V().isAuthorized('OP_FINISH_500'), false)
  assert.match(X().downloadRecipe('OP_FINISH_500').error, /not authorized/)
  assert.equal(V().sign('OP_FINISH_500', 'ENGINEER', true, '').ok, false, 'a comment is required')
  assert.equal(value(V().sign('OP_FINISH_500', 'ENGINEER', true, 'looks good')), 'authorized')
  value(X().downloadRecipe('OP_FINISH_500'))
  assert.equal(V().sign('OP_FINISH_500', 'ENGINEER', false, 'no').ok, false, 'a downloaded recipe cannot be rejected')
  assert.equal(V().clearSignature('OP_FINISH_500', 'ENGINEER').ok, false)
  value(V().setAuthorization(true, [{ name: 'ENGINEER', lock: 'VC_SET_LABEL' }, { name: 'QA', lock: 'VC_ROLLBACK_ITEMS' }], true))
  assert.equal(V().isAuthorized('OP_FINISH_500'), false, 'adding a signer un-authorizes every recipe')
  assert.match(X().downloadRecipe('OP_FINISH_500').error, /not authorized/)
  assert.ok(X().downloadRecipe('OP_FINISH_500', { proceedUnauthorized: true }).ok)
  assert.deepEqual(V().approvalReport(true).map(r => r.recipe), ['OP_FINISH_500'])
  assert.equal(V().approvalReport(false)[0].signatures, 'ENGINEER: Pending; QA: Pending')
}, { full: true }))

