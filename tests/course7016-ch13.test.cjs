test('Chapter 13 workshop: check out FIC-404, add two input parameters, differences, check in, history, rollback', () => fixture(() => {
  enable()
  assert.match(M().addInputParameter('FIC-404', 'EXTRA1') ?? '', /not checked out/, 'Manual preference: the module must be checked out first')
  value(V().checkOut(FIC))
  assert.equal(V().isCheckedOut(FIC), 'ADMINISTRATOR')
  assert.equal(M().addInputParameter('FIC-404', 'EXTRA1'), null)
  const d1 = value(V().diff(FIC, 1, 'current'))
  assert.equal(d1.same, false)
  assert.ok(d1.lines.some(l => l.kind === 'added' && /EXTRA1/.test(l.text)))
  assert.match(d1.left, /Version 1/); assert.match(d1.right, /current/)
  assert.equal(M().addInputParameter('FIC-404', 'EXTRA2'), null)
  assert.match(M().addInputParameter('FIC-404', 'EXTRA2') ?? '', /already exists/)
  assert.ok(value(V().diff(FIC, 1, 'current')).lines.some(l => l.kind === 'added' && /EXTRA2/.test(l.text)))
  value(V().checkIn(FIC, 'two input parameters'))
  assert.equal(V().isCheckedOut(FIC), null)
  assert.equal(value(V().diff(FIC, 2, 'current')).same, true, 'no differences after the check in')
  const hist = V().history(FIC)
  assert.deepEqual(hist.map(v => v.n), [2, 1])
  assert.equal(hist[0].comment, 'two input parameters')
  assert.equal(value(V().diff(FIC, 1, 2)).same, false)
  value(V().rollback(FIC, 1))
  assert.equal(V().isCheckedOut(FIC), 'ADMINISTRATOR', 'a rolled back item stays checked out until it is checked in')
  assert.equal((M().modules['FIC-404'].inputParams ?? []).length, 0, 'the extra parameters are gone')
  value(V().checkIn(FIC, 'rolled back'))
  assert.deepEqual(V().history(FIC).map(v => v.n), [3, 2, 1])
  assert.equal(value(V().diff(FIC, 1, 3)).same, true, 'version 3 equals version 1')
  const checks = checkCourse7016Ch13(V())
  assert.deepEqual(checks.filter(c => ['7016-13a-1', '7016-13a-2', '7016-13b-1', '7016-13b-2', '7016-13b-3', '7016-13b-4', '7016-13b-5'].includes(c.id) && c.verdict !== 'verified').map(c => c.id), [])
}))

