const assert = require('node:assert/strict')
const test = require('node:test')
const { fixture } = require('./helpers/dv09-fixture.cjs')
const { checkDv09Ch9 } = require('../src/renderer/src/engine/dv09Ch9Checks.ts')
const { DV09_CH9 } = require('../src/renderer/src/engine/dv09Ch9.ts')
const { DV09_CHAPTERS } = require('../src/renderer/src/engine/dv09Registry.ts')
const { usePictures } = require('../src/renderer/src/engine/pictureStore.ts')
const { useStore } = require('../src/renderer/src/engine/store.ts')
const { useSecurity } = require('../src/renderer/src/engine/security.ts')
const setup = require('./helpers/dv09-ch9-setup.cjs')

const CTL = 'CTLR_PAINT', CARD = CTL + '/C05'
const ds = over => ({ name: 'DS01', description: '', direction: 'OUTPUT', outputMode: 'COMPLETE_BLOCK', outputReadback: false, dataType: 'INT16', tag: 'FLOW-OUT',
  plcTable: 'HOLDING_REGISTERS', plcBase: 0, plcOffset: 0, count: 1, ...over })
const P1 = { enabled: true, protocol: 'RTU', mode: 'MASTER', retryCount: 1, timeoutMs: 1000, transmitDelayMs: 0, portType: 'RS232', baud: 9600, parity: 'EVEN', dataBits: 8, stopBits: 1 }
const P2 = { enabled: true, protocol: 'RTU', mode: 'SLAVE', transmitDelayMs: 0, portType: 'RS232', baud: 9600, parity: 'EVEN', dataBits: 8, stopBits: 1 }
const run = (ctx, s) => { ctx.useStore.setState({ running: true }); for (let i = 0; i < s * 10; i++) ctx.M().tick(0.1) }
const verdicts = ctx => Object.fromEntries(checkDv09Ch9(ctx.M(), usePictures.getState().pictures).map(c => [c.id, c.verdict]))
const pend = v => Object.entries(v).filter(([, x]) => x === 'pending').map(([k]) => k)
const ok = (r, w) => assert.equal(r, null, w ?? String(r))

test('chapter 9 registry: workshops, unique step ids and a check for every step that is not tick-only', () => fixture(2, ctx => {
  assert.equal(DV09_CHAPTERS.find(c => c.number === 9), DV09_CH9)
  const ws = DV09_CH9.module.workshops
  assert.deepEqual(ws.map(w => w.id), ['dv09-ch9-reading', 'dv09-ch9-modbus'])
  assert.ok(ws.every(w => w.id.startsWith('dv09-ch9-')))
  const ids = ws.flatMap(w => w.steps.map(s => s.id))
  assert.equal(new Set(ids).size, ids.length)
  assert.ok(ids.filter(i => /^dv09-9[wmf]-/.test(i)).every(i => /^dv09-9[wmf]-\d+$/.test(i)))
  const checks = DV09_CH9.check({ main: ctx.M(), security: {}, system: {}, library: ctx.L() })
  assert.equal(checks.length, 23)
  const checked = new Set(checks.map(c => c.id))
  for (const id of checked) assert.ok(ids.includes(id), id)
  const tickOnly = ids.filter(i => !checked.has(i))
  assert.deepEqual(tickOnly.filter(i => !i.startsWith('dv09-9r-')), ['dv09-9w-2'], 'only the physical card insertion is tick-only besides the reading items')
  assert.equal(pend(verdicts(ctx)).length, 23, 'nothing is verified from the chapter 2 state')
}))

test('chapter 9 Workshop 1: the serial card, ports, devices and datasets are verified one by one', () => fixture(2, ctx => {
  const M = ctx.M
  assert.match(M().configureSerialPort(CARD, 'P01', P1), /does not exist/)
  assert.match(M().addSerialCard(CTL, 1, true), /already has a card/)
  assert.match(M().addSerialCard(CTL, 9, true), /1-8/)
  ok(M().addSerialCard(CTL, 5, true))
  let v = verdicts(ctx)
  assert.equal(v['dv09-9w-3'], 'verified')
  assert.equal(v['dv09-9w-1'], 'pending')
  ok(M().configureSerialCard(CARD, { tieback: true }))
  assert.equal(verdicts(ctx)['dv09-9w-1'], 'verified')
  // port 1: a wrong value keeps the step pending
  ok(M().configureSerialPort(CARD, 'P01', { ...P1, baud: 19200 }))
  assert.equal(verdicts(ctx)['dv09-9w-4'], 'pending')
  ok(M().configureSerialPort(CARD, 'P01', { ...P1, sendOutputsOnStartup: false }))
  assert.equal(verdicts(ctx)['dv09-9w-4'], 'verified', 'send outputs on startup is the student choice')
  ok(M().configureSerialPort(CARD, 'P01', { enabled: false }))
  assert.equal(verdicts(ctx)['dv09-9w-4'], 'pending', 'a disabled port does not count')
  ok(M().configureSerialPort(CARD, 'P01', P1))
  assert.match(M().configureSerialPort(CARD, 'P02', { ...P2, dataBits: 7 }), /RTU requires 8 data bits/)
  ok(M().configureSerialPort(CARD, 'P02', { ...P2, mode: 'MASTER' }))
  assert.equal(verdicts(ctx)['dv09-9w-5'], 'pending', 'port 2 must be the slave')
  ok(M().configureSerialPort(CARD, 'P02', P2))
  assert.equal(verdicts(ctx)['dv09-9w-5'], 'verified')
  // devices
  assert.match(M().addSerialDevice(CARD, 'P01', 'DEV01', 0), /1 to 247/)
  ok(M().addSerialDevice(CARD, 'P01', 'DEV01', 2, 'MODICON MICRO'))
  assert.equal(verdicts(ctx)['dv09-9w-6'], 'pending', 'the device must be at address 1')
  ok(M().updateSerialDevice(CARD, 'P01', 'DEV01', { address: 1 }))
  assert.equal(M().hardware.serialCards[CARD].configured.ports.P01.devices.DEV01.description, 'MODICON MICRO')
  assert.equal(verdicts(ctx)['dv09-9w-6'], 'verified')
  assert.match(M().addSerialDevice(CARD, 'P01', 'DEV02', 1), /already used|single serial device/)
  ok(M().addSerialDevice(CARD, 'P02', 'DEV01', 1))
  assert.equal(verdicts(ctx)['dv09-9w-8'], 'verified')
  // datasets
  ok(M().saveSerialDataset(CARD, 'P01', 'DEV01', ds({ name: 'DS01', tag: 'FLOW-OUT' })))
  assert.equal(verdicts(ctx)['dv09-9w-7'], 'pending', 'one dataset is not enough')
  assert.match(M().saveSerialDataset(CARD, 'P01', 'DEV01', ds({ name: 'DS02', tag: 'MTR-OUT', dataType: 'INT16', plcTable: 'COILS', plcOffset: 1 })), /Boolean/)
  ok(M().saveSerialDataset(CARD, 'P01', 'DEV01', ds({ name: 'DS02', tag: 'MTR-OUT', dataType: 'BOOLEAN', plcTable: 'COILS', plcOffset: 0 })))
  assert.equal(verdicts(ctx)['dv09-9w-7'], 'pending', 'coil offset 0 is not the offset 1 of the table')
  ok(M().saveSerialDataset(CARD, 'P01', 'DEV01', ds({ name: 'DS02', tag: 'MTR-OUT', dataType: 'BOOLEAN', plcTable: 'COILS', plcOffset: 1 }), 'DS02'))
  assert.equal(verdicts(ctx)['dv09-9w-7'], 'verified')
  ok(M().saveSerialDataset(CARD, 'P02', 'DEV01', ds({ name: 'DS01', tag: 'FLOW-IN', direction: 'INPUT' })))
  ok(M().saveSerialDataset(CARD, 'P02', 'DEV01', ds({ name: 'DS02', tag: 'MTR-IN', direction: 'INPUT', dataType: 'BOOLEAN', plcTable: 'COILS', plcOffset: 1 })))
  assert.equal(verdicts(ctx)['dv09-9w-9'], 'verified')
  // download
  assert.equal(verdicts(ctx)['dv09-9w-10'], 'pending')
  ok(M().downloadSerialCard(CARD))
  assert.equal(verdicts(ctx)['dv09-9w-10'], 'verified')
  ok(M().configureSerialPort(CARD, 'P01', { retryCount: 2 }))
  assert.equal(verdicts(ctx)['dv09-9w-10'], 'pending', 'an edit after the download needs a new download')
  assert.equal(verdicts(ctx)['dv09-9w-4'], 'pending')
}))

