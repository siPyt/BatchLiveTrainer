test('chapter 9 modules: MTR-MODBUS and FIC-MODBUS checks follow the bindings, the downloads and the operation', () => fixture(2, ctx => {
  const M = ctx.M
  // the whole serial part first (the setup helper repeats it, so build it by hand here)
  ok(M().addSerialCard(CTL, 5, true))
  ok(M().configureSerialCard(CARD, { tieback: true }))
  ok(M().configureSerialPort(CARD, 'P01', P1)); ok(M().configureSerialPort(CARD, 'P02', P2))
  for (const p of ['P01', 'P02']) ok(M().addSerialDevice(CARD, p, 'DEV01', 1))
  ok(M().saveSerialDataset(CARD, 'P01', 'DEV01', ds({ name: 'DS01', tag: 'FLOW-OUT' })))
  ok(M().saveSerialDataset(CARD, 'P01', 'DEV01', ds({ name: 'DS02', tag: 'MTR-OUT', dataType: 'BOOLEAN', plcTable: 'COILS', plcOffset: 1 })))
  ok(M().saveSerialDataset(CARD, 'P02', 'DEV01', ds({ name: 'DS01', tag: 'FLOW-IN', direction: 'INPUT' })))
  ok(M().saveSerialDataset(CARD, 'P02', 'DEV01', ds({ name: 'DS02', tag: 'MTR-IN', direction: 'INPUT', dataType: 'BOOLEAN', plcTable: 'COILS', plcOffset: 1 })))
  ok(M().downloadSerialCard(CARD)); run(ctx, 3)
  let v
  // MTR-MODBUS
  ok(M().createModule({ tag: 'MTR-MODBUS', type: 'MOTOR', area: 'PLANT_AREA_A', description: 'Pump on Modbus coils' }) ? null : 'create')
  assert.equal(verdicts(ctx)['dv09-9m-1'], 'verified')
  assert.equal(verdicts(ctx)['dv09-9m-3'], 'pending')
  ok(M().enableDeviceLifecycle('MTR-MODBUS') ? null : 'lifecycle')
  ok(M().editDeviceDraft('MTR-MODBUS', { controllerTag: CTL, inputDst: 'MTR-IN/R2', outputDst: 'MTR-OUT/R2', resetRequired: false }) ? null : 'draft')
  assert.equal(verdicts(ctx)['dv09-9m-3'], 'pending', 'the binding applies at the download')
  assert.equal(verdicts(ctx)['dv09-9m-4'], 'verified')
  ok(M().saveDeviceConfiguration('MTR-MODBUS') ? null : 'save')
  ok(M().downloadDeviceConfiguration('MTR-MODBUS') ? null : 'download')
  ok(M().setDeviceOnline('MTR-MODBUS', true) ? null : 'online')
  v = verdicts(ctx)
  assert.deepEqual(['dv09-9m-3', 'dv09-9m-5'].map(k => v[k]), ['verified', 'verified'])
  assert.equal(v['dv09-9m-8'], 'pending')
  run(ctx, 2); M().startMotor('MTR-MODBUS'); run(ctx, 2)
  assert.equal(verdicts(ctx)['dv09-9m-8'], 'pending', 'started but not stopped')
  M().stopMotor('MTR-MODBUS'); run(ctx, 2)
  assert.equal(verdicts(ctx)['dv09-9m-8'], 'verified')
  // dynamo and display
  usePictures.getState().createPicture('Tank101')
  assert.equal(verdicts(ctx)['dv09-9m-6'], 'pending')
  assert.ok(usePictures.getState().addElement('TANK101', { type: 'pump', x: 200, y: 300, tag: 'MTR-MODBUS' }))
  assert.equal(verdicts(ctx)['dv09-9m-6'], 'verified')
  assert.equal(verdicts(ctx)['dv09-9m-7'], 'pending')
  assert.equal(usePictures.getState().savePicture('TANK101'), true)
  assert.equal(verdicts(ctx)['dv09-9m-7'], 'verified')
  // FIC-MODBUS
  assert.equal(M().createModule({ tag: 'FIC-MODBUS', type: 'PID', templateId: 'PID_LOOP', area: 'PLANT_AREA_A', description: 'MODBUS loop' }), true)
  assert.equal(M().bindAnalogDst('FIC-MODBUS', 'input', 'FLOW-IN/R40001'), true)
  assert.equal(M().bindAnalogDst('FIC-MODBUS', 'output', 'FLOW-OUT/R40001'), true)
  assert.equal(M().enablePidLifecycle('FIC-MODBUS'), true)
  assert.equal(M().savePidConfiguration('FIC-MODBUS'), true)
  assert.equal(M().downloadPidModule('FIC-MODBUS'), true)
  assert.equal(M().setPidLifecycleOnline('FIC-MODBUS', true), true)
  v = verdicts(ctx)
  assert.deepEqual(['dv09-9f-1', 'dv09-9f-3', 'dv09-9f-4', 'dv09-9f-5'].map(k => v[k]), ['verified', 'verified', 'verified', 'verified'])
  assert.equal(v['dv09-9f-8'], 'pending')
  run(ctx, 1); M().setMode('FIC-MODBUS', 'MAN'); run(ctx, 0.5); M().setOutput('FIC-MODBUS', 40); run(ctx, 3)
  assert.equal(ctx.M().hardware.serialCards[CARD].runtime.memory.P02['1']['HOLDING_REGISTERS:0'], 40)
  assert.equal(verdicts(ctx)['dv09-9f-8'], 'verified')
  assert.equal(M().modules['FIC-MODBUS'].pv, 40)
  // a broken link breaks the loop verdict
  ok(M().configureSerialCard(CARD, { tieback: false })); ok(M().downloadSerialCard(CARD)); run(ctx, 5)
  assert.equal(verdicts(ctx)['dv09-9f-8'], 'pending', 'no tie-back, no good PV')
}))

