test('Checkout negative cases: a one-terminator segment fails the termination check, a missing reconnect fails voltage and waveform', () => fixture(2, () => {
  enableFieldbus(); wire()
  rigApi.rigPlug('trunk-mb', null)
  assert.equal(verdicts()['dv09-12w-7'], 'pending', 'removing the cable is not yet a checkout')
  rigApi.rigHubTerminator(false)
  assert.equal(verdicts()['dv09-12w-10'], 'pending')
  rigApi.rigHubTerminator(true)
  assert.equal(verdicts()['dv09-12w-10'], 'verified')
  rigApi.rigPlug('terminator2', 'jb-S1')
  assert.equal(model.evalRig(rigApi.getRig()).totalTerminators, 3)
  assert.equal(verdicts()['dv09-12w-10'], 'pending', 'three terminators are too many')
  // a recording taken with the wrong setup cannot be stored
  rigApi.rigMeterPress('power', 0); rigApi.rigMeterPress('inputA', 0); for (let i = 0; i < 5; i++) rigApi.rigMeterPress('down', 0); rigApi.rigMeterPress('F4', 0)
  rigApi.rigSetLead('a', 'sig+', 0); rigApi.rigSetLead('com', 'sig-', 0)
  assert.match(rigApi.rigRecord(1), /5 micro farads/)
  const waveBefore = model.meterReading({ ...rigApi.getRig().meter, mode: 'scope', coupling: 'AC', screen: 'main', on: true }, { ...rigApi.getRig(), plugs: { ...rigApi.getRig().plugs, 'trunk-mb': 'mb-seg' } }, 0)
  assert.equal(waveBefore.value, 470, 'three terminators shrink the waveform')
  rigApi.rigPlug('terminator2', null)
  const one = model.meterReading({ ...rigApi.getRig().meter, mode: 'scope', coupling: 'AC', screen: 'main', on: true }, { ...rigApi.getRig(), hubTerminator: false, plugs: { ...rigApi.getRig().plugs, 'trunk-mb': 'mb-seg' } }, 0)
  assert.ok(one.value > 900, 'one terminator gives a larger waveform than the expected 500-900 mV')
}))

