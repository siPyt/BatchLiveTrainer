test('Verify communications: the 3144P appears only after the card is downloaded and the port rescanned, and drops when the wiring is broken', () => fixture(2, () => {
  enableFieldbus(); wire()
  assert.equal(M().autoSenseController(NAME), true)
  assert.equal(act.configureH1Port(CARD, 'P01', { enabled: true }), null)
  assert.equal(act.downloadH1Card(CARD), null)
  assert.match(act.rescanPort(CARD, 'P02'), /not enabled/)
  assert.equal(verdicts()['dv09-12w-13'], 'pending')
  tick(0.4)
  let rows = act.ffInventory(M().hardware.h1Cards[CARD], 'P01')
  assert.equal(rows.length === 0 || rows[0].state === 'Not communicating', true, 'the LAS has not probed address 33 yet')
  tick(12)
  rows = act.ffInventory(M().hardware.h1Cards[CARD], 'P01')
  assert.deepEqual(rows.map(r => [r.address, r.state, r.integrity, r.model]), [[33, 'Standby', 'Good', '3144P temperature transmitter']])
  assert.equal(act.rescanPort(CARD, 'P01'), null)
  assert.equal(verdicts()['dv09-12w-13'], 'verified')
  rigApi.rigPlug('spur-jb', null)
  tick(1)
  rows = act.ffInventory(M().hardware.h1Cards[CARD], 'P01')
  assert.equal(rows[0].state, 'Not communicating')
  assert.equal(verdicts()['dv09-12w-13'], 'pending')
  rigApi.rigPlug('spur-jb', 'jb-S2')
  tick(40)
  assert.equal(act.ffInventory(M().hardware.h1Cards[CARD], 'P01')[0].state, 'Standby')
  // removing the segment cable for the checkout isolates the field wiring: the device drops off the bus
  rigApi.rigPlug('trunk-mb', null)
  tick(1)
  assert.equal(act.ffInventory(M().hardware.h1Cards[CARD], 'P01')[0].state, 'Not communicating')
}))

